import { useState, useEffect, useContext } from 'react';
import { Link } from 'react-router-dom';
import axios from 'axios';
import AuthContext from '../context/AuthContext';
import { Plus, History, AlertTriangle, CheckCircle, Smartphone, MoreVertical, Trash2, FileText } from 'lucide-react';

const FarmerDashboard = () => {
    const { user } = useContext(AuthContext);
    const [history, setHistory] = useState([]);
    const [loading, setLoading] = useState(true);
    const [openMenuId, setOpenMenuId] = useState(null);

    const fetchHistory = async () => {
        try {
            const token = JSON.parse(localStorage.getItem('userInfo'))?.token;
            const config = {
                headers: {
                    Authorization: `Bearer ${token}`,
                },
            };
            const { data } = await axios.get('/api/detect/history', config);
            setHistory(data);
        } catch (error) {
            console.error('Error fetching history:', error);
        } finally {
            setLoading(false);
        }
    };

    useEffect(() => {
        if (user) {
            fetchHistory();
        }

        const handleClickOutside = () => setOpenMenuId(null);
        document.addEventListener('click', handleClickOutside);
        return () => document.removeEventListener('click', handleClickOutside);
    }, [user]);

    const handleDelete = async (id) => {
        if (!window.confirm('Are you sure you want to delete this scan?')) return;

        try {
            const token = JSON.parse(localStorage.getItem('userInfo'))?.token;
            const config = {
                headers: {
                    Authorization: `Bearer ${token}`,
                },
            };
            await axios.delete(`/api/detect/${id}`, config);
            fetchHistory();
        } catch (error) {
            console.error('Error deleting scan:', error);
            alert('Failed to delete scan.');
        }
    };

    const handleExportPDF = (scan) => {
        const printWindow = window.open('', '_blank');
        printWindow.document.write(`
            <html>
                <head><title>CropGuard Scan Report</title></head>
                <body style="font-family: sans-serif; padding: 40px;">
                    <h1 style="color: #059669;">CropGuard Scan Report</h1>
                    <hr/>
                    <p><strong>Date:</strong> ${new Date(scan.date).toLocaleString()}</p>
                    <p><strong>Crop Type:</strong> ${scan.cropType}</p>
                    <p><strong>Detected Health:</strong> ${scan.detectedDisease}</p>
                    <p><strong>Confidence Score:</strong> ${scan.confidenceScore}%</p>
                    <hr/>
                    <p>This report was generated by Anti Gravity Agricultural Assistant.</p>
                </body>
            </html>
        `);
        printWindow.document.close();
        printWindow.print();
    };

    return (
        <div className="max-w-7xl mx-auto px-4 py-8">
            <div className="flex flex-col md:flex-row justify-between items-center mb-10">
                <div>
                    <h1 className="text-4xl font-extrabold text-nature-900 tracking-tight">
                        <span className="flex items-center gap-2">Hello, <span className="text-nature-600">{user?.name}</span></span>
                    </h1>
                    <p className="text-stone-500 mt-2 text-lg">
                        Welcome to your farm management center.
                    </p>
                </div>

                <Link to="/scan" className="btn-primary flex items-center gap-2 mt-6 md:mt-0 animate-fade-in">
                    <Plus size={20} /> New Scan
                </Link>
            </div>

            <div>
                <h2 className="text-2xl font-bold text-stone-800 mb-6 flex items-center gap-3">
                    <div className="p-2 bg-nature-100 rounded-lg"><History className="text-nature-600" size={24} /></div>
                    Recent Scans
                </h2>

                {loading ? (
                    <div className="flex justify-center p-12"><div className="animate-spin rounded-full h-12 w-12 border-b-2 border-nature-600"></div></div>
                ) : history.length === 0 ? (
                    <div className="text-center py-16 bg-white rounded-2xl border-2 border-dashed border-stone-200 shadow-sm">
                        <div className="bg-stone-50 w-20 h-20 rounded-full flex items-center justify-center mx-auto mb-4">
                            <Smartphone className="h-10 w-10 text-stone-400" />
                        </div>
                        <p className="text-stone-500 font-medium text-lg">No scans yet.</p>
                        <Link to="/scan" className="text-nature-600 font-bold hover:underline mt-2 inline-block">Start your first scan</Link>
                    </div>
                ) : (
                    <div className="grid md:grid-cols-2 lg:grid-cols-3 gap-8">
                        {history.map((scan) => (
                            <div key={scan._id} className="card relative overflow-hidden group hover:shadow-nature-200/50 p-0 border-0">
                                <div className={`absolute top-4 left-4 px-3 py-1 text-xs font-bold text-white rounded-full shadow-md z-10 ${scan.status === 'completed' ? (scan.detectedDisease === 'Healthy' ? 'bg-gradient-to-r from-nature-500 to-nature-600' : 'bg-gradient-to-r from-red-500 to-red-600') :
                                    scan.status === 'pending_review' ? 'bg-amber-500' :
                                        'bg-blue-500'
                                    }`}>
                                    {scan.status === 'completed' || scan.status === 'resolved'
                                        ? (scan.detectedDisease === 'Healthy' ? 'Healthy' : 'Infected')
                                        : 'Under Review'}
                                </div>

                                {/* Three-dot Menu */}
                                <div className="absolute top-4 right-4 z-20">
                                    <button
                                        onClick={(e) => {
                                            e.stopPropagation();
                                            setOpenMenuId(openMenuId === scan._id ? null : scan._id);
                                        }}
                                        className="p-1 bg-white/80 hover:bg-white rounded-full shadow-sm text-stone-600 transition-colors"
                                    >
                                        <MoreVertical size={18} />
                                    </button>

                                    {openMenuId === scan._id && (
                                        <div className="absolute right-0 mt-2 w-48 bg-white rounded-xl shadow-xl border border-stone-100 overflow-hidden animate-fade-in text-left">
                                            <button
                                                onClick={() => handleExportPDF(scan)}
                                                className="w-full text-left px-4 py-3 text-stone-700 hover:bg-stone-50 flex items-center gap-3 transition-colors"
                                            >
                                                <FileText size={16} className="text-nature-600" />
                                                <span className="text-sm font-medium">Export to PDF</span>
                                            </button>
                                            <button
                                                onClick={() => handleDelete(scan._id)}
                                                className="w-full text-left px-4 py-3 text-red-600 hover:bg-red-50 flex items-center gap-3 transition-colors border-t border-stone-50"
                                            >
                                                <Trash2 size={16} />
                                                <span className="text-sm font-medium">Delete</span>
                                            </button>
                                        </div>
                                    )}
                                </div>

                                <div className="h-48 overflow-hidden relative">
                                    <div className="absolute inset-0 bg-black/10 group-hover:bg-black/0 transition-colors"></div>
                                    {scan.inputImageUrl ? (
                                        <img src={`${scan.inputImageUrl}`} alt="Crop" className="w-full h-full object-cover transform group-hover:scale-110 transition-transform duration-500" />
                                    ) : (
                                        <div className="w-full h-full flex items-center justify-center bg-stone-100 text-stone-400">No Image</div>
                                    )}
                                </div>
                                <div className="p-6">
                                    <h3 className="font-bold text-xl text-stone-800 mb-1">{scan.cropType}</h3>
                                    <p className={`font-medium ${scan.detectedDisease === 'Healthy' ? 'text-nature-600' : 'text-red-500'}`}>{scan.detectedDisease}</p>

                                    <div className="flex justify-between items-center mt-6 pt-4 border-t border-stone-100">
                                        {scan.status === 'pending_review' ? (
                                            <span className="text-amber-600">Waiting for Expert</span>
                                        ) : (
                                            <>
                                                {scan.detectedDisease === 'Healthy' ? <CheckCircle size={14} className="text-nature-500" /> : <AlertTriangle size={14} className="text-amber-500" />}
                                                <span>{scan.confidenceScore}% Confidence</span>
                                            </>
                                        )}
                                    </div>
                                    <span className="text-xs text-stone-400 font-medium">{new Date(scan.date).toLocaleDateString()}</span>
                                </div>

                                {scan.adminComment && (
                                    <div className="bg-blue-50 p-3 rounded-lg text-sm text-blue-800 mt-4 border border-blue-100">
                                        <strong className="block mb-1 text-blue-900 text-xs uppercase tracking-wide">Admin Note:</strong>
                                        {scan.adminComment}
                                    </div>
                                )}
                            </div>
                        ))}
                    </div>
                )}
            </div>
        </div>
    );
};

export default FarmerDashboard;
